#!/usr/bin/env bash
# Задача 5: аргументы командной строки.
printf 'Имя скрипта: %s\n' "$0"
printf 'Количество: %s\n' "$#"
printf 'Все аргументы: %s\n' "$*"
if (( $# > 0 )); then
  printf 'Первый: %s\n' "$1"
  printf 'Последний: %s\n' "${@: -1}"
else
  printf 'Первый: отсутствует\nПоследний: отсутствует\n'
fi
